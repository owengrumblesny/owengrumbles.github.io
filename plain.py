"""Build the plain version of The Catacombs.

  site/catacombs/plain.html   every file as a bare HTML list
  site/catacombs/files.json   every file as data, for scripts

The plain page has no CSS, no JavaScript, no web fonts, and no images, so it
works in terminal browsers (lynx, w3m, links) and is easy to scrape.
Both files are generated by build.py, so never edit them by hand.
"""

import html
import json
import urllib.parse

SITE_URL = "https://owengrumblesny.github.io/"


def build_plain(root, groups, human_size):
    out_dir = root / "catacombs"
    total = sum(len(files) for _, _, files in groups)

    parts = []
    files_json = []
    if not total:
        parts.append("<p>Nothing buried here yet.</p>")
    for group, title, files in groups:
        parts.append(f"<h2>{html.escape(title)} ({len(files)})</h2>\n<ul>")
        for rel, size in files:
            path = "files/" + "/".join(urllib.parse.quote(p) for p in rel.parts)
            ext = rel.suffix.lstrip(".").upper() or "FILE"
            parts.append(f'<li><a href="{html.escape(path, quote=True)}">{html.escape(rel.as_posix())}</a> '
                         f'({ext}, {human_size(size)})</li>')
            files_json.append({
                "folder": group,
                "path": rel.as_posix(),
                "name": rel.name,
                "type": ext,
                "size_bytes": size,
                "url": SITE_URL + "catacombs/" + path,
            })
        parts.append("</ul>")

    body = "\n".join(parts)
    page = f"""<!DOCTYPE html>
<!-- Generated by build.py. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>The Catacombs (plain) - Owen Grumbles</title>
</head>
<body>
<p><a href="./">Full Catacombs</a> | <a href="../">Home</a> | <a href="files.json">files.json</a></p>
<hr>
<h1>The Catacombs</h1>
<p>Every file, no styling. {total} file(s).</p>
{body}
<hr>
<p>Owen Grumbles. My own writing here is CC BY 4.0; my own artwork and graphics are all rights reserved. Anything made by someone else belongs to them.</p>
</body>
</html>
"""
    (out_dir / "plain.html").write_text(page, encoding="utf-8")

    data = {"site": SITE_URL, "count": total, "files": files_json}
    (out_dir / "files.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return total
