"""Build the plain version of the site in site/plain/.

Plain pages are bare HTML: no CSS, no JavaScript, no web fonts, no layout.
They work in terminal browsers (lynx, w3m, links) and are easy to read
from a script. Everything here is generated from the main site by build.py,
so never edit site/plain/ by hand; it is deleted and rebuilt every time.

  site/plain/index.html                 home page
  site/plain/philosophy.html            philosophy articles
  site/plain/history.html               history articles
  site/plain/articles.html              every article
  site/plain/catacombs.html             every Catacombs file
  site/plain/<section>/<article>.html   each article, text only
  site/plain/index.json                 articles and files as data, for scripts
"""

import datetime
import html
import json
import re
import shutil
import urllib.parse

SITE_URL = "https://owengrumblesny.github.io/"

FOOTER = ("&copy; 2026 Owen Grumbles. Code: GPL-3.0. Writings: CC BY 4.0. "
          "Graphics and assets: all rights reserved.")


def clean(fragment):
    """Strip a piece of the main site's HTML down to plain markup."""
    s = re.sub(r"<!--.*?-->", "", fragment, flags=re.DOTALL)
    s = re.sub(r"<(script|style)\b.*?</\1>", "", s, flags=re.DOTALL | re.IGNORECASE)
    s = re.sub(r"<meta\b[^>]*>", "", s, flags=re.IGNORECASE)
    s = re.sub(r'<a class="back"[^>]*>.*?</a>', "", s, flags=re.DOTALL)
    # Drop styling hooks; keep href, src, alt, and the like
    s = re.sub(r'\s(?:class|style|id|role|aria-[\w-]+)="[^"]*"', "", s)
    # Spans only carried styling, so keep their text and lose the tags
    s = re.sub(r"</?span>", "", s)
    # Headings that were links on the main site become plain headings
    s = re.sub(r"<(h\d)><a [^>]*>(.*?)</a></\1>", r"<\1>\2</\1>", s, flags=re.DOTALL)
    # Tidy indentation and blank lines
    lines = [line.strip() for line in s.splitlines()]
    return "\n".join(line for line in lines if line)


def section_body(page_text, section_id):
    """Inner HTML of <section id="..."> on a main-site page."""
    found = re.search(r'<section id="' + re.escape(section_id) + r'"[^>]*>(.*?)</section>',
                      page_text, re.DOTALL)
    return found.group(1) if found else ""


def intro(page_text, section_id):
    """The text between a section's heading and its auto-built list."""
    body = section_body(page_text, section_id)
    body = re.sub(r"^.*?</h2>", "", body, count=1, flags=re.DOTALL)
    body = body.split("<!--", 1)[0]
    return clean(body)


def page(title, root, content):
    nav = " | ".join([
        f'<a href="{root}index.html">Home</a>',
        f'<a href="{root}philosophy.html">Philosophy</a>',
        f'<a href="{root}history.html">History</a>',
        f'<a href="{root}articles.html">All Articles</a>',
        f'<a href="{root}catacombs.html">Catacombs</a>',
        f'<a href="{root}../">Full site</a>',
    ])
    return f"""<!DOCTYPE html>
<!-- Generated by build.py from the main site. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(title)}</title>
</head>
<body>
<p>{nav}</p>
<hr>
{content}
<hr>
<p>{FOOTER} <a href="{root}index.json">index.json</a></p>
</body>
</html>
"""


def article_list(articles, root, show_section):
    if not articles:
        return "<p>No articles yet.</p>"
    items = []
    for a in articles:
        href = html.escape(f"{root}{a['section']}/{urllib.parse.quote(a['file'])}", quote=True)
        bits = []
        if show_section:
            bits.append(f"[{a['section'].title()}]")
        bits.append(f'<a href="{href}">{html.escape(a["title"])}</a>')
        if a["date"]:
            bits.append(f"({a['date'].isoformat()})")
        line = " ".join(bits)
        if a["description"]:
            line += f"<br>\n{html.escape(a['description'])}"
        items.append(f"<li>{line}</li>")
    return "<ul>\n" + "\n".join(items) + "\n</ul>"


def build_plain(root, sections, articles_by_section, catacomb_groups, human_size):
    out = root / "plain"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir()

    everything = sorted(
        (a for arts in articles_by_section.values() for a in arts),
        key=lambda a: (a["date"] is None, -(a["date"] or datetime.date.min).toordinal(), a["title"].lower()),
    )

    # Home page: the same sections as the main home page, in the same order
    home = (root / "index.html").read_text(encoding="utf-8")
    parts = ["<h1>Owen Grumbles</h1>"]
    for sid, plain_page in [("philosophy", "philosophy.html"), ("history", "history.html"),
                            ("catacombs", "catacombs.html"), ("contact", None), ("license", None)]:
        body = clean(section_body(home, sid))
        if not body:
            continue
        parts.append(body)
        if plain_page:
            parts.append(f'<p><a href="{plain_page}">Go to {sid.title()}</a></p>')
    (out / "index.html").write_text(page("Owen Grumbles", "", "\n".join(parts)), encoding="utf-8")

    # Section pages and plain copies of each article
    for section, name in sections.items():
        main_page = (root / section / "index.html").read_text(encoding="utf-8")
        arts = articles_by_section.get(section, [])
        content = f"<h1>{html.escape(name)}</h1>\n{intro(main_page, section)}\n" + article_list(arts, "", False)
        (out / f"{section}.html").write_text(page(f"{name} - Owen Grumbles", "", content), encoding="utf-8")

        (out / section).mkdir(exist_ok=True)
        for a in arts:
            text = (root / section / "articles" / a["file"]).read_text(encoding="utf-8")
            found = re.search(r"<article\b[^>]*>(.*?)</article>", text, re.DOTALL)
            body = clean(found.group(1)) if found else f"<h1>{html.escape(a['title'])}</h1>"
            full = f'../../{section}/articles/{urllib.parse.quote(a["file"])}'
            body += (f'\n<p><a href="../{section}.html">Back to {html.escape(name)}</a> | '
                     f'<a href="{full}">Full version</a></p>')
            # Plain articles sit two folders below site/, the same depth as the
            # originals, so relative links and images inside them still work
            (out / section / a["file"]).write_text(page(f"{a['title']} - Owen Grumbles", "../", body),
                                                   encoding="utf-8")

    # Every article
    articles_page = (root / "articles" / "index.html").read_text(encoding="utf-8")
    content = f"<h1>All Articles</h1>\n{intro(articles_page, 'all-articles')}\n" + article_list(everything, "", True)
    (out / "articles.html").write_text(page("All Articles - Owen Grumbles", "", content), encoding="utf-8")

    # Catacombs
    cat_page = (root / "catacombs" / "index.html").read_text(encoding="utf-8")
    parts = ["<h1>The Catacombs</h1>", intro(cat_page, "catacombs")]
    files_json = []
    if not catacomb_groups:
        parts.append("<p>Nothing buried here yet.</p>")
    for group, title, files in catacomb_groups:
        parts.append(f"<h2>{html.escape(title)} ({len(files)})</h2>\n<ul>")
        for rel, size in files:
            url = "catacombs/files/" + "/".join(urllib.parse.quote(p) for p in rel.parts)
            ext = rel.suffix.lstrip(".").upper() or "FILE"
            parts.append(f'<li><a href="../{html.escape(url, quote=True)}">{html.escape(rel.as_posix())}</a> '
                         f'({ext}, {human_size(size)})</li>')
            files_json.append({
                "folder": group,
                "path": rel.as_posix(),
                "name": rel.name,
                "type": ext,
                "size_bytes": size,
                "url": SITE_URL + url,
            })
        parts.append("</ul>")
    (out / "catacombs.html").write_text(page("The Catacombs - Owen Grumbles", "", "\n".join(parts)),
                                        encoding="utf-8")

    # Data for scripts
    data = {
        "site": SITE_URL,
        "plain": SITE_URL + "plain/",
        "articles": [
            {
                "section": a["section"],
                "title": a["title"],
                "date": a["date"].isoformat() if a["date"] else None,
                "description": a["description"] or None,
                "url": SITE_URL + f"{a['section']}/articles/{urllib.parse.quote(a['file'])}",
                "plain_url": SITE_URL + f"plain/{a['section']}/{urllib.parse.quote(a['file'])}",
            }
            for a in everything
        ],
        "catacombs": files_json,
    }
    (out / "index.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    return len(everything), len(files_json)
